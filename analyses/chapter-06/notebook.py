"""Chapter 6 — Safety (first-pass scaffold: the spine test).

Angle (`measuring_livability.md` §4): *safety is broader than crime
statistics.* The series' recurring move — the headline metric points away
from the thing it claims to measure — applied to the crime rate. The claim:
**the map of crime is not the map of danger.** New Yorkers face several
different kinds of harm, generated by different forces, and they do not
co-locate.

Goal of this first pass (mirrors Ch. 2/3/4/5): validate the chapter's spine
BEFORE any visual work. Measured spine = **three kinds of harm**, each per
1,000 residents:

  1. violent crime  — person felonies (murder/rape/robbery/felony assault)
  2. traffic KI     — pedestrian + cyclist casualties (killed or injured)
  3. property crime — burglary + grand larceny (+ of motor vehicle)

Kill criterion (series standard): if any pair co-ranks |rho| >= 0.75
(Spearman, n = 59 CDs), the spine collapses. AT-RISK PAIR = violent ~
property (they share the NYPD reporting pipeline). Traffic KI is expected to
stay orthogonal to (or invert) both crime axes — that independence is the
chapter. If violent ~ property merge, the chapter becomes a clean 2-axis
"reported crime vs. traffic" story (an acceptable outcome). A perceived-
safety overlay (DOHMH CHS 2016) is added AFTER this checkpoint, not here.

Normalization (locked): per-1,000 residents (B01003), cross-axis comparable.
Traffic per-street-mile cross-check + a daytime-population caveat for
commercial cores are follow-ups, not part of the spine test.

Data window: 2022-01-01 .. 2024-12-31 (annualized), fixed so per-CD rates
are stable, not single-year noise.

Run with::

    python analyses/chapter-06/notebook.py

Outputs (out/ inside this dir):
  facts.json    Per-CD per-axis rates + the spine-test matrix.
  rankings.csv  Long-form per-CD per-axis rates + ranks (sortable for QA).

METHOD NOTE (Punch list): tract_to_cd / per_cd_population / _assign_cd are
copied from Ch. 4/5 notebooks — this is the 4th reuse; promote to
shared/access.py as its own commit. Kept as a copy here to avoid touching
Ch. 4/5 mid-kickoff.
"""

